typedef int (*at_read_code_fn)(uintptr_t address, void *buffer, size_t size);

/** Verify all build 25480438 engine RVA byte pins via safe read_code; returns 1 on exact match. */
static inline int atst_verify_code_pins(at_read_code_fn read_code_cb, uintptr_t engine_base, uint32_t *failed_rva) {
    unsigned char buf[32];
    if (!read_code_cb || !engine_base) {
        if (failed_rva) *failed_rva = 0u;
        return 0;
    }
    for (size_t i = 0; i < sizeof(AT_CODE_PINS) / sizeof(AT_CODE_PINS[0]); i++) {
        const at_code_pin *pin = &AT_CODE_PINS[i];
        if (read_code_cb(engine_base + pin->rva, buf, pin->size) != 0 ||
            memcmp(buf, pin->bytes, pin->size) != 0) {
            if (failed_rva) *failed_rva = pin->rva;
            return 0;
        }
    }
    return 1;
}


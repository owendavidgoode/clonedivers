using System.Text.Json;
using System.Text.RegularExpressions;

namespace Clonedivers;

public static class LinuxRecording
{
    const string Header = "#!/bin/sh\n# Clonedivers capture wrapper";
    public static string Root(string gameDir) => FileSafety.Child(gameDir, "mods_diagnostics");
    public static string Setup(string gameDir, Settings settings)
    {
        var root = Root(gameDir);
        if (root.IndexOfAny(new[] { '\r', '\n' }) >= 0) throw new InvalidDataException("Recording paths cannot contain line breaks.");
        Directory.CreateDirectory(root);
        var sessions = FileSafety.Child(root, "sessions"); Directory.CreateDirectory(sessions);
        var script = FileSafety.Child(root, "steam-capture.sh");
        if (File.Exists(script) && !LinuxSupport.Tail(script, 32768).StartsWith(Header, StringComparison.Ordinal))
            throw new IOException("A custom steam-capture.sh already exists. Move it aside before setting up recording.");
        LinuxSupport.WritePrivate(script, Script.Replace("\r\n", "\n"));
        if (OperatingSystem.IsLinux()) File.SetUnixFileMode(script, UnixFileMode.UserRead | UnixFileMode.UserWrite | UnixFileMode.UserExecute);
        RefreshSelection(gameDir, settings);
        return Quote(script) + " %command%";
    }

    public static string Quote(string value) => "'" + value.Replace("'", "'\"'\"'", StringComparison.Ordinal) + "'";
    public static string? ArmedSession(string gameDir)
    {
        var marker = FileSafety.Child(Root(gameDir), "record-next");
        if (!File.Exists(marker)) return null;
        var id = LinuxSupport.Tail(marker, 128).Trim();
        if (!Regex.IsMatch(id, "^[a-f0-9]{32}$")) throw new InvalidDataException("Invalid recording request. Cancel it and arm a new recording.");
        var session = FileSafety.Child(Path.Combine(Root(gameDir), "sessions"), id);
        FileSafety.RejectLink(Path.GetDirectoryName(session)!);
        return session;
    }

    public static string Arm(string gameDir, Settings settings)
    {
        Setup(gameDir, settings);
        if (ArmedSession(gameDir) is not null) throw new IOException("A recording is already armed. Launch the game or use record-cancel first.");
        var id = Guid.NewGuid().ToString("N");
        var session = FileSafety.Child(Path.Combine(Root(gameDir), "sessions"), id); Directory.CreateDirectory(session);
        Directory.CreateDirectory(FileSafety.Child(session, "proton")); Directory.CreateDirectory(FileSafety.Child(session, "mangohud"));
        LinuxSupport.WritePrivate(Path.Combine(session, "selection.json"), JsonSerializer.Serialize(LinuxSupport.Selection(gameDir, settings), new JsonSerializerOptions { WriteIndented = true }));
        // MangoHud handles per-frame sampling and writes its own summary. No FPS or quality overrides.
        LinuxSupport.WritePrivate(Path.Combine(session, "MangoHud.conf"), $"no_display\nautostart_log=1\nlog_duration=600\nlog_interval=0\npermit_upload=0\noutput_folder={Path.Combine(session, "mangohud")}\n");
        using (var marker = new FileStream(FileSafety.Child(Root(gameDir), "record-next"), FileMode.CreateNew, FileAccess.Write))
        using (var writer = new StreamWriter(marker)) writer.WriteLine(id);
        LinuxSupport.Record("record-armed", "Next Steam launch will capture MangoHud and Proton logs.");
        return session;
    }

    public static void Cancel(string gameDir)
    {
        var marker = FileSafety.Child(Root(gameDir), "record-next");
        if (File.Exists(marker)) File.Delete(marker);
        LinuxSupport.Record("record-cancelled", "Pending recording cancelled. Existing session files retained.");
    }

    public static void RefreshSelection(string gameDir, Settings settings)
    {
        var root = Root(gameDir);
        if (Directory.Exists(root)) LinuxSupport.WritePrivate(FileSafety.Child(root, "selection.json"), JsonSerializer.Serialize(LinuxSupport.Selection(gameDir, settings)));
    }

    public static string? LatestSession(string gameDir)
    {
        var root = FileSafety.Child(Root(gameDir), "sessions");
        if (!Directory.Exists(root)) return null;
        var sessions = Directory.EnumerateDirectories(root).Where(p => Regex.IsMatch(Path.GetFileName(p), "^[a-f0-9]{32}$")).ToList();
        foreach (var session in sessions) FileSafety.RejectLink(session);
        // Prefer an actually started capture over a request that has not run yet.
        return sessions.OrderByDescending(p => File.Exists(Path.Combine(p, "status.txt"))).ThenByDescending(Directory.GetLastWriteTimeUtc).FirstOrDefault();
    }

    // Kept in the game library so Flatpak Steam can execute it without needing the host .NET binary.
    internal const string Script = """
        #!/bin/sh
        # Clonedivers capture wrapper — generated by recording setup.
        # No armed request: forward Steam's command and environment unchanged.
        [ "$#" -gt 0 ] || { echo 'No Steam command was provided.' >&2; exit 64; }
        root=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd -P) || exit 1
        request="$root/record-next"
        [ -f "$request" ] && [ ! -L "$request" ] || exec "$@"
        IFS= read -r id < "$request"
        case "$id" in *[!a-f0-9]*|'') echo 'Invalid recording request; launching normally.' >&2; exec "$@";; esac
        [ "${#id}" -eq 32 ] || exec "$@"
        session="$root/sessions/$id"
        [ ! -L "$root/sessions" ] && [ -d "$session" ] && [ ! -L "$session" ] && [ ! -L "$session/proton" ] && [ ! -L "$session/mangohud" ] && [ -f "$session/MangoHud.conf" ] && [ ! -L "$session/MangoHud.conf" ] && [ ! -L "$session/status.txt" ] && [ ! -L "$session/proton-version.txt" ] && [ ! -L "$session/selection-at-launch.json" ] || exec "$@"
        # Claim once. Concurrent launches cannot both consume the same request.
        mkdir "$root/claim-$id" 2>/dev/null || exec "$@"
        mv "$request" "$session/request.claimed" || { rmdir "$root/claim-$id"; exec "$@"; }
        rmdir "$root/claim-$id"
        umask 077
        printf 'Capture started: %s\nSteam environment: %s\n' "$(date -u +%FT%TZ)" "${FLATPAK_ID:-${SNAP_NAME:-native or unspecified}}" > "$session/status.txt"
        if [ -f "$root/selection.json" ] && [ ! -L "$root/selection.json" ]; then cp "$root/selection.json" "$session/selection-at-launch.json"; fi
        for argument in "$@"; do
          case "$argument" in */proton) version="$(dirname -- "$argument")/version"; if [ -f "$version" ]; then head -c 4096 "$version" > "$session/proton-version.txt"; fi;; esac
        done
        # Existing user overrides are unchanged on ordinary launches. This opt-in capture uses its own config.
        unset MANGOHUD_CONFIG MANGOHUD_PRESETSFILE
        MANGOHUD=1 MANGOHUD_CONFIGFILE="$session/MangoHud.conf" PROTON_LOG=1 PROTON_LOG_DIR="$session/proton" "$@"
        result=$?
        printf 'Steam command exit code: %s\nCapture finished: %s\n' "$result" "$(date -u +%FT%TZ)" >> "$session/status.txt"
        if ! find "$session/mangohud" -maxdepth 1 -type f -name '*.csv' -print -quit | grep -q .; then
          printf 'No MangoHud CSV was produced. Check that the Vulkan layer is installed and visible to Steam. Gamescope needs a separate mangoapp integration.\n' >> "$session/status.txt"
        fi
        exit "$result"
        """;
}
